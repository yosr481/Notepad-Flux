// Generates src/utils/emojiTable.js from the gemoji devDependency. Run: node scripts/gen-emoji-table.mjs
// Output is committed; the app never imports gemoji. One line per emoji: "<emoji> <name> <alias> ...".
import { writeFileSync } from 'node:fs';
import { gemoji } from 'gemoji';

const lines = gemoji.map((g) => [g.emoji, ...g.names].join(' ')).join('\n');
const out = `// GENERATED by scripts/gen-emoji-table.mjs from gemoji (MIT, ${gemoji.length} emoji). Do not edit.
const DATA = ${JSON.stringify(lines)};

const table = new Map();
for (const line of DATA.split('\\n')) {
    const [emoji, ...names] = line.split(' ');
    for (const name of names) table.set(name, emoji);
}

// Exact-case lookup over gemoji names and aliases; undefined for unknown or non-string input.
export const emojiFor = (name) => (typeof name === 'string' ? table.get(name) : undefined);
`;
writeFileSync(new URL('../src/utils/emojiTable.js', import.meta.url), out);
